import re
from pathlib import Path
from typing import TextIO

from titanfp.fpbench.fpcast import FPCore

from fpy2 import Function
from fpy2.ast import FuncDef
from fpy2.utils import pythonize_id

_HEADER = '''"""
FPy ports of the FPBench file `{}`.

Generated by `python -m infra.fpbench`; do not edit.
"""

from fpy2 import *
'''

def module_name(path: Path) -> str:
    """Name of the Python module porting the FPCore file at `path`."""
    return path.stem.replace('-', '_')

def port_names(cores: list[FPCore]) -> list[str]:
    """Python names of the ports of `cores`, unique within the list."""
    names: list[str] = []
    for i, core in enumerate(cores):
        if core.ident is not None:
            # other cores call it by this name
            name = pythonize_id(core.ident)
        elif core.name is not None:
            name = re.sub(r'\W+', '_', core.name.value.value).strip('_')
        else:
            name = f'f{i}'
        while name in names:
            name += '_'
        names.append(name)
    return names

def write_ports(path: Path, cores: list[FPCore], f: TextIO):
    """Writes a Python module porting `cores` from the FPCore file at `path`."""
    print(_HEADER.format(path.name), file=f)
    for core, name in zip(cores, port_names(cores)):
        func = Function.from_fpcore(core, default_name=name, ignore_unknown=True)
        # properties that are functions come first
        meta = func.ast.meta
        for prop in [v for v in (meta.pre, meta.spec) if isinstance(v, FuncDef)]:
            print(f'\n{prop.format()}\n', file=f)
        print(f'\n{func.format()}\n', file=f)
